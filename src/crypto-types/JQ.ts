// 构建反向映射
const REVERSE_JQ_MAP: { [key: string]: string } = {};
Object.entries(JQ_MAP).forEach(([char, code]) => {
    REVERSE_JQ_MAP[code] = char;
});

/**
 * Encode text to JQ format
 */
const encode = (text: string): string => {
    return text.split('').map(char => {
        return JQ_MAP[char] || char;
    }).join(' ');
};

/**
 * Decode JQ format to text
 */
const decode = (text: string): string => {
    return text.split(' ').map(token => {
        return REVERSE_JQ_MAP[token] || token;
    }).join('');
};

/**
 * Detect if text is in JQ format
 */
const detect = (text: string): boolean => {
    // JQ format consists mainly of quotes and spaces
    return /^[ '"\\s]+$/.test(text) && 
           text.split(' ').some(token => Object.keys(REVERSE_JQ_MAP).includes(token));
};

export {
    encode,
    decode,
    detect
};

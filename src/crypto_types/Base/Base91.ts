const is_Base91 = (str: string): boolean => {
    if (str.length === 0) return false;
    for (const c of str) {
        if (BASE91_TABLE[c.charCodeAt(0) - 32] === undefined) return false;
    }
    return true;
};

const de_Base91 = (str: string): string => {
    const result: number[] = [];
    let buffer = 0;
    let bits = 0;
    let value = 0;
    let count = 0;

    for (const c of str) {
        if (c === '\n' || c === '\r' || c === ' ') continue;

        const decoded = BASE91_TABLE[c.charCodeAt(0) - 32];
        if (decoded === undefined) continue;

        if ((count & 1) !== 0) {
            value = (decoded << bits) | value;
            buffer = (buffer << 13) | value;
            bits += 13;
        } else {
            value = decoded;
            bits = 6;
        }

        while (bits >= 8) {
            bits -= 8;
            result.push((buffer >>> bits) & 0xFF);
        }

        count++;
    }

    if ((count & 1) !== 0) {
        buffer = (buffer << 7) | value;
        bits += 7;
        while (bits >= 8) {
            bits -= 8;
            result.push((buffer >>> bits) & 0xFF);
        }
    }

    return Buffer.from(result).toString();
};

const en_Base91 = (str: string): string => {
    const result: string[] = [];
    let buffer = 0;
    let bits = 0;
    let count = 0;

    for (const b of Buffer.from(str)) {
        buffer |= (b << bits);
        bits += 8;

        if (bits > 13) {
            const remainder = bits & 7;
            const v = buffer & ((1 << remainder) - 1);
            buffer >>= remainder;
            bits -= remainder;

            result.push(String.fromCharCode(BASE91_TABLE[buffer % 91]));
            buffer = Math.floor(buffer / 91);

            if (remainder > 0) {
                for (let i = 0; i < remainder; i++) {
                    bits += 13;
                    while (bits > 13) {
                        const val = buffer % 91;
                        buffer = Math.floor(buffer / 91);
                        result.push(String.fromCharCode(BASE91_TABLE[((val << 7) | v) % 91]));
                    }
                }
            }
        }
    }

    if (bits > 0) {
        buffer |= (1 << bits);
        while (bits > 7) {
            const val = buffer % 91;
            buffer = Math.floor(buffer / 91);
            result.push(String.fromCharCode(BASE91_TABLE[val]));
            bits -= 7;
        }
    }

    if ((count & 1) !== 0) {
        const val = buffer % 91;
        buffer = Math.floor(buffer / 91);
        result.push(String.fromCharCode(BASE91_TABLE[val]));
    }

    return result.join('');
};

